"""Generate only the inspected selected offsets; this is not a silicon model."""
import argparse,json
from pathlib import Path
def render(value):
    lines=['/* Generated by generate_registers.py from registers.json. */','#ifndef PL_REGISTERS_H','#define PL_REGISTERS_H']
    seen=set()
    for row in value['maps']:
        name=row['name']
        if name not in ('F439','G474') or name in seen:raise ValueError('map identity')
        seen.add(name)
        if any(type(row[k]) is not int or row[k]<0 or row[k]>255 for k in ('status','data','txe','tc')):raise ValueError('map field')
        if row['status']%4 or row['data']%4 or row['status']==row['data']:raise ValueError('register alignment/alias')
        if not row['txe'] or not row['tc'] or row['txe']&row['tc']:raise ValueError('flag overlap')
        for k in ('status','data','txe','tc'):lines.append('#define PL_'+name+'_'+k.upper()+' '+str(row[k])+'u')
    if seen!={'F439','G474'}:raise ValueError('missing map')
    return '\n'.join(lines+['#endif',''])
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();root=Path(__file__).resolve().parent;target=root/'registers.h';text=render(json.loads((root/'registers.json').read_text()))
    if a.check:
        if target.read_text()!=text:raise SystemExit('generated header differs')
    else:target.write_text(text)
if __name__=='__main__':main()
